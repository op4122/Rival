// Writes app/config.js from environment variables (or a local .env file).
// Locally: copy .env.example to .env, then `npm run config`. In CI the deploy workflow sets the variables from secrets.
// Every value here is a public, front-end-safe key. Never put the Supabase secret / service_role key here.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const env = { ...process.env };
if (existsSync('.env')) for (const line of readFileSync('.env', 'utf8').split(/\r?\n/)) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/); if (m && !env[m[1]]) env[m[1]] = m[2].replace(/^["']|["']$/g, '');
}
const cfg = {
  supabaseUrl: env.SUPABASE_URL || '',
  supabaseKey: env.SUPABASE_PUBLISHABLE_KEY || '',
  posthogKey: env.POSTHOG_KEY || '',
  posthogHost: env.POSTHOG_HOST || '',
};
if (/service_role|sb_secret_/.test(cfg.supabaseKey)) { console.error('Refusing to write a secret key into front-end config.'); process.exit(1); }
writeFileSync('app/config.js', `// Generated by scripts/write-config.mjs. Public, front-end-safe keys only: committed so GitHub Pages can serve it.\nwindow.RIVAL_CONFIG = ${JSON.stringify(cfg, null, 2)};\n`);
console.log('app/config.js written:', Object.entries(cfg).map(([k, v]) => `${k}=${v ? 'set' : 'empty'}`).join(', '));
