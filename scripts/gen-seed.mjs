// Builds supabase/migrations/*_seed_exercises.sql from the app's own exercise library (app/index.html),
// so names, slugs and muscle tags in the database always match what the app and its heat map use.
// Run after changing LIB, ATT or EACH in the app:  node scripts/gen-seed.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
const src = readFileSync('app/index.html', 'utf8');
const grab = (name, open, close) => {
  const i = src.indexOf(`const ${name} = ${open}`); if (i < 0) throw new Error('missing ' + name);
  let d = 0, j = src.indexOf(open, i);
  for (let k = j; k < src.length; k++) { if (src[k] === open) d++; else if (src[k] === close && --d === 0) return src.slice(j, k + 1); }
  throw new Error('unclosed ' + name);
};
const MUSCLES = Function(`return ${grab('MUSCLES', '{', '}')}`)();
const MUSC = Function(`return ${grab('MUSC', '{', '}')}`)();
const LIB = Function(`return ${grab('LIB', '[', ']')}`)();
const ATT = Function(`return ${grab('ATT', '{', '}')}`)();
const EACH = new Set(Function(`return ${src.match(/const EACH = new Set\((\[[^\]]*\])\)/)[1]}`)());
const slug = s => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 20) || 'x';
const groups = list => [...new Set(list.map(x => MUSC[x]).filter(Boolean))];
const rows = [];
for (const [, , , prim, sec, free, mach] of LIB) {
  const p = groups(prim), s = groups(sec).filter(g => !p.includes(g));
  for (const [v, kind] of [[free, 'free'], [mach, 'mach']]) {
    const [id, n, inc, c, bw] = v;
    const base = { slug: id, name: n, p, s, equipment: bw ? 'bodyweight' : kind === 'free' ? 'free_weight' : 'machine', inc, c: !!c, ea: EACH.has(id), att: null, base: null };
    rows.push(base);
    for (const a of ATT[id] || []) rows.push({ ...base, slug: id + '__' + slug(a), name: `${n} (${a})`, att: a, base: id });
  }
}
const q = s => s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`;
const arr = a => `array[${a.map(q).join(', ')}]::text[]`;
const values = rows.map(r => `  (${q(r.slug)}, ${q(r.name)}, ${arr(r.p)}, ${arr(r.s)}, ${q(r.equipment)}, ${r.inc}, ${r.c}, ${r.ea}, ${q(r.att)}, ${q(r.base)})`).join(',\n');
const sql = `-- Built-in exercise library, generated by scripts/gen-seed.mjs from app/index.html. Do not edit by hand.
-- ${rows.length} rows: ${LIB.length} movements with a free-weight and a machine option each, plus cable attachment variants.
-- Muscle tags use the heat map's ${Object.keys(MUSCLES).length} groups: ${Object.keys(MUSCLES).join(', ')}.
insert into public.exercises (slug, name, primary_muscles, secondary_muscles, equipment, increment_kg, is_compound, per_side, attachment, base_slug)
values
${values}
on conflict (slug) where user_id is null do update set
  name = excluded.name, primary_muscles = excluded.primary_muscles, secondary_muscles = excluded.secondary_muscles,
  equipment = excluded.equipment, increment_kg = excluded.increment_kg, is_compound = excluded.is_compound,
  per_side = excluded.per_side, attachment = excluded.attachment, base_slug = excluded.base_slug;
`;
const dir = 'supabase/migrations', existing = readdirSync(dir).find(f => f.endsWith('_seed_exercises.sql'));
const file = `${dir}/${existing || '20261022120100_seed_exercises.sql'}`;
writeFileSync(file, sql);
writeFileSync('supabase/muscles.json', JSON.stringify(Object.keys(MUSCLES), null, 2) + '\n');
console.log(`${file}: ${rows.length} exercises; supabase/muscles.json: ${Object.keys(MUSCLES).length} muscle groups`);
